def password_is_hashed(password):
    """
    Returns a boolean of whether password is hashed with loaded algorithms
    """
    if password is None:
        return False
    try:
        hasher = identify_hasher(password)
    except ValueError:
        # hasher can't be identified or is not loaded
        return False
    return hasher.algorithm in get_hashers_by_algorithm().keys()


def password_is_usable(password):
    """
    Returns True if password is None or wasn't generated by django.contrib.auth.hashers.make_password(None)
    """
    unusable_password_len = len(UNUSABLE_PASSWORD_PREFIX) + UNUSABLE_PASSWORD_SUFFIX_LENGTH

    # what are the odds that a user password starts with unusable prefix and the same length :-?
    return password is None or not (password.startswith(UNUSABLE_PASSWORD_PREFIX) and len(password) == unusable_password_len)


class User(AbstractDABUser, CommonModel, AuditableModel):
    ignore_relations = [
        'groups',  # not using the auth app stuff, see Team model
        'user_permissions',  # not using auth app permissions
        'logentry',  # used for Django admin pages, not the API
        'social_auth',  # Social auth endpoint
        'organizations_administered',  # We are going to merge [teams|orgs] the user is an admin in with [teams|orgs] the user is a member of
        'teams_administered',
        'authenticator_users',  # private model .This is not a model we want on the user endpoint. We actually pull this information up into the user payload
    ]
    activity_stream_excluded_field_names = ['last_login']

    encrypted_fields = ()  # handed as special case by UserSerializer
    PASSWORD_FIELDS = ["password"]  # Mark password fields so ansible_base.lib.rest_filters can properly block attempts to filter over password

    resource = AnsibleResourceField(primary_key_field="id")

    managed = models.BooleanField(
        editable=False,
        blank=False,
        default=False,
        help_text=_("Indicates if this user is managed by the system. It cannot be modified once created."),
    )

    # By default, skip managed users (use all_objects for all users queryset)
    objects = UserUnmanagedManager()

    def __init__(self, *args, is_platform_auditor=False, **kwargs):
        super().__init__(*args, **kwargs)
        if is_platform_auditor:
            self._is_platform_auditor = True
        # Store the original value of the fields to check for field changes later
        self._original_fields = self._get_fields()

    def _get_fields(self):
        """
        Return a dictionary of the model's instance fields and their current values.
        """
        return {field.name: self.__dict__.get(field.name) for field in self._meta.fields}

    def fetch_platform_auditor_membership(self):
        "Get from the database True or False, this user is a system auditor"
        from aap_gateway_api.utils.rbac import get_platform_auditor_role

        rd = get_platform_auditor_role()
        return self.role_assignments.filter(role_definition=rd).exists()

    def apply_platform_auditor_membership(self, value):
        from aap_gateway_api.utils.rbac import get_platform_auditor_role

        """Change RBAC SystemAuditor role to reflect given value"""
        rd = get_platform_auditor_role()
        prior_value = self.fetch_platform_auditor_membership()
        if bool(prior_value) != bool(value):
            if prior_value:
                self.role_assignments.filter(role_definition=rd).delete()
            else:
                rd.give_global_permission(self)

        self._is_platform_auditor = value

    def save(self, *args, **kwargs):
        is_new_user = bool(not self.pk)

        # If the password is empty string lets make it None, this will get turned into an unusable password by make_password
        if self.password == '':
            self.password = None

        if password_is_usable(self.password) and not password_is_hashed(self.password):
            self.password = make_password(self.password)

        # Verify if the user's information has been updated for existing and unmanaged users.
        # If yes, invalidated jwt cache
        if not is_new_user and not self.managed:
            fields = ["username", "first_name", "last_name", "email", "is_superuser"]
            fields_changed = any(self._original_fields[field] != getattr(self, field) for field in fields)

            if fields_changed:
                from aap_gateway_api.utils.jwt_cache import invalidate_cached_jwt

                invalidate_cached_jwt(self)

        super().save(*args, **kwargs)

        # If the system auditor role was set on unsaved object, apply it now that it is saved
        if is_new_user and hasattr(self, '_is_platform_auditor'):
            self.apply_platform_auditor_membership(self._is_platform_auditor)

    def logout(self):
        logger.debug(f"Logging out user {self.username} from any active backends")
        # cookies = Cookie.objects.filter(user=self)
        # for cookie in cookies:
        #    cookie.logout()

    def summary_fields(self):
        return user_summary_fields(self)

    def get_authenticator_ids(self) -> list[int]:
        return list(self.authenticator_users.values_list('provider__id', flat=True))

    def get_authenticator_uids(self) -> list[str]:
        return list(self.authenticator_users.values_list('uid', flat=True).distinct())

    def get_is_platform_auditor(self):
        if not hasattr(self, '_is_platform_auditor'):
            # For performance purposes, catch the value from the database
            self._is_platform_auditor = self.fetch_platform_auditor_membership()
        return self._is_platform_auditor

    def set_is_platform_auditor(self, value):
        if not self.pk:
            # For unsaved objects, delay application of membership, used in save method
            self._is_platform_auditor = value
            return

        if (not hasattr(self, '_is_platform_auditor')) or bool(self._is_platform_auditor) != bool(value):
            self.apply_platform_auditor_membership(value)

    def del_is_platform_auditor(self):
        if hasattr(self, '_is_platform_auditor'):
            del self._is_platform_auditor

    is_platform_auditor = property(get_is_platform_auditor, set_is_platform_auditor, del_is_platform_auditor)

    @property
    def organizations(self):
        from aap_gateway_api.models import Organization

        return Organization.access_qs(self, 'member')

    @property
    def is_system_auditor(self):
        """Temporary shim to satisfy ansible_base.lib.utils.views.permissions.IsSuperuserOrAuditor"""
        return self.is_platform_auditor

    @property
    def is_migrated(self):
        return str(self.resource.service_id) == str(service_id())


